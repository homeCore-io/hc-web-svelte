/**
 * The UI server in production (S1): the built app, `/ui/…` (inside the app),
 * homeCore passed through, live video passed to go2rtc (`video.js`), and
 * camera events' stills kept for a week (`stills.js`).
 * Run with `node server/index.js` after a build.
 */
import { mkdirSync } from 'node:fs';
import { createServer } from 'node:http';
import { coreUrl, dataDir } from './config.js';
import { isCorePath, proxyRequest, proxyUpgrade } from './proxy.js';
import { isVideoPath, videoRequest, videoUpgrade } from './video.js';
import { isStillsPath, startStills, stillsRequest } from './stills.js';

// Generated by `vite build`. Loaded at run time rather than imported, so type
// checking the server doesn't wander into the build's output.
/** @type {{ handler: (req: import("node:http").IncomingMessage, res: import("node:http").ServerResponse, next: () => void) => void }} */
const { handler } = await import(new URL('../build/handler.js', import.meta.url).href);

mkdirSync(dataDir(), { recursive: true });

const server = createServer((req, res) => {
	if (isCorePath(req.url)) return void proxyRequest(req, res, coreUrl());
	if (isVideoPath(req.url)) return void videoRequest(req, res, coreUrl());
	if (isStillsPath(req.url)) return void stillsRequest(req, res, coreUrl());
	handler(req, res, () => {
		res.writeHead(404).end();
	});
});

server.on('upgrade', (req, socket, head) => {
	if (isCorePath(req.url)) return void proxyUpgrade(req, socket, head, coreUrl());
	if (isVideoPath(req.url)) return void videoUpgrade(req, socket, head, coreUrl());
	socket.destroy();
});

const port = Number(process.env.PORT ?? 3000);
const host = process.env.HOST ?? '0.0.0.0';
// Each camera event's still, copied here before the plugin rolls it over.
startStills({ core: coreUrl() });

server.listen(port, host, () => {
	console.log(`hc-web on ${host}:${port}, homeCore at ${coreUrl()}, data in ${dataDir()}`);
});
