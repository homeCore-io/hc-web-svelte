<!--
	A device's details (D3): its main control, large; every other control and
	action it declares; its readings; a day's history; recent activity saying
	who changed it; and the housekeeping folded under More. All generated by
	`detailsFor` — this only draws it and sends what is asked.
-->
<script lang="ts">
	import X from '@lucide/svelte/icons/x';
	import Power from '@lucide/svelte/icons/power';
	import Play from '@lucide/svelte/icons/play';
	import Pause from '@lucide/svelte/icons/pause';
	import SkipBack from '@lucide/svelte/icons/skip-back';
	import SkipForward from '@lucide/svelte/icons/skip-forward';
	import { actionBody, detailsFor, ready, type ActionView } from '#lib/details.js';
	import { activityOf, type StateEvent } from '#lib/activity.js';
	import { withPending } from '#lib/pending.js';
	import { roomOf } from '#lib/summary.js';
	import { commands } from '#lib/commands.svelte.js';
	import { devices } from '#lib/devices.svelte.js';
	import { rooms } from '#lib/rooms.svelte.js';
	import { clock } from '#lib/clock.svelte.js';
	import type { CoreDevice } from '#lib/devices.js';
	import BigBar from './BigBar.svelte';
	import Chart from './Chart.svelte';
	import Icon from './Icon.svelte';
	import Art from './Art.svelte';
	import Toggle from './Toggle.svelte';
	import { goAhead } from '#lib/ask.js';
	import { core } from '#lib/core.svelte.js';

	let { device, onclose }: { device: CoreDevice; onclose: () => void } = $props();

	const id = $derived(device.device_id);
	const view = $derived(detailsFor(device, Object.values(devices.byId), clock.now));
	const pending = $derived(commands.pending[id]);
	const card = $derived(withPending(view.card, pending));
	const note = $derived(commands.notes[id]);
	const room = $derived(roomOf(device, rooms.list));
	const off = $derived(!device.available);
	const want = (attr: string, value: unknown) => pending?.want[attr] ?? value;

	const brightness = $derived(
		card.extras.find((e) => e.kind === 'slider' && e.attr === 'brightness_pct')
	);

	function set(values: Record<string, unknown>) {
		void commands.set(id, card.kind, values, device.attributes);
	}

	// ---- actions ----
	let values = $state<Record<string, Record<string, unknown>>>({});
	let ran = $state<string | null>(null);
	async function run(a: ActionView) {
		if (!(await goAhead(id, card.kind, `${a.label} — ${card.name}?`, a.confirm))) return;
		if (await commands.act(id, a.id, withoutAction(actionBody(a, values[a.id] ?? {})))) {
			ran = a.id;
			setTimeout(() => {
				if (ran === a.id) ran = null;
			}, 1500);
		}
	}
	const withoutAction = (body: Record<string, unknown>) => {
		const { action: _drop, ...rest } = body;
		return rest;
	};
	const field = (a: string, name: string, v: unknown) =>
		(values = { ...values, [a]: { ...(values[a] ?? {}), [name]: v } });

	// ---- activity ----
	let activity = $state<StateEvent[] | null>(null);
	$effect(() => {
		const which = id;
		let gone = false;
		activity = null;
		fetch(
			`/api/v1/events?device_id=${encodeURIComponent(which)}&type=device_state_changed&limit=40`
		)
			.then((r) => (r.ok ? r.json() : []))
			.then((rows: { event: StateEvent }[]) => {
				if (!gone) activity = rows.map((r) => r.event);
			})
			.catch(() => {
				if (!gone) activity = [];
			});
		return () => (gone = true);
	});
	const lines = $derived(activityOf(activity ?? [], device.schema ?? { attributes: {} }));
	const time = (iso: string) => {
		const d = new Date(iso);
		const today = new Date().toDateString() === d.toDateString();
		return today
			? d.toLocaleTimeString([], { hour: 'numeric', minute: '2-digit' })
			: d.toLocaleDateString([], { weekday: 'short', hour: 'numeric', minute: '2-digit' });
	};

	// ---- colour ----
	const SWATCHES: [string, string, { x: number; y: number }][] = [
		['Warm white', '#ffd9a0', { x: 0.4596, y: 0.4105 }],
		['Soft white', '#fff1de', { x: 0.4148, y: 0.3959 }],
		['Daylight', '#e4eeff', { x: 0.3127, y: 0.329 }],
		['Red', '#e5484d', { x: 0.675, y: 0.322 }],
		['Orange', '#f5903d', { x: 0.5562, y: 0.4084 }],
		['Green', '#3fae5a', { x: 0.2151, y: 0.7106 }],
		['Blue', '#3e7bfa', { x: 0.167, y: 0.04 }],
		['Purple', '#8e4ec6', { x: 0.2725, y: 0.1096 }]
	];
	const near = (a: { x: number; y: number } | null | undefined, b: { x: number; y: number }) =>
		!!a && Math.abs(a.x - b.x) < 0.02 && Math.abs(a.y - b.y) < 0.02;
</script>

<header>
	<span
		class="icon"
		class:lit={card.tone === 'on' && !card.art}
		class:alert={card.tone === 'alert'}
		class:art={!!card.art}
	>
		<Art src={card.art} logo={card.artLogo} icon={card.icon} size={22} />
	</span>
	<div class="title">
		<h2 id="details-title">{view.name}</h2>
		<p class:alert={card.tone === 'alert'} class:note>
			{#if card.waiting}<span class="working" aria-label="Waiting for the house"></span>{/if}
			{[room?.name, note ?? card.stateLine].filter(Boolean).join(' · ')}
		</p>
	</div>
	<button class="close" aria-label="Close" onclick={onclose}><X size={22} /></button>
</header>

<div class="body">
	{#if card.art}
		<!-- Made afresh per track, so one that wouldn't load doesn't hide the next. -->
		{#key card.art}
			<img
				class="cover"
				class:logo={card.artLogo}
				src={card.art}
				alt=""
				onerror={(e) => ((e.currentTarget as HTMLImageElement).hidden = true)}
			/>
		{/key}
	{/if}
	<!-- The main control, large. -->
	{#if brightness && brightness.kind === 'slider' && card.control?.kind === 'switch'}
		{@const sw = card.control}
		<div class="hero-row">
			<BigBar
				label="Brightness"
				value={sw.on ? brightness.value : 0}
				min={0}
				max={brightness.max}
				unit="%"
				disabled={off}
				oncommit={(v) => set(v <= 0 ? { on: false } : { brightness_pct: v, on: true })}
			/>
			<button
				class="power"
				class:on={sw.on}
				aria-pressed={sw.on}
				aria-label="Power"
				disabled={off}
				onclick={async () => {
					if (await goAhead(id, card.kind, `Turn ${card.name} ${sw.on ? 'off' : 'on'}?`))
						set({ on: !sw.on });
				}}><Power size={22} /></button
			>
		</div>
	{:else if card.control?.kind === 'switch'}
		{@const sw = card.control}
		<div class="row big">
			<span>{sw.on ? 'On' : 'Off'}</span>
			<Toggle
				on={sw.on}
				label={view.name}
				disabled={off}
				onchange={async (on) => {
					if (await goAhead(id, card.kind, `Turn ${card.name} ${on ? 'on' : 'off'}?`))
						set({ [sw.attr]: on });
				}}
			/>
		</div>
	{:else if card.control?.kind === 'lock'}
		{@const lk = card.control}
		<button
			class="wide"
			disabled={off}
			onclick={async () => {
				if (lk.locked && !(await goAhead(id, card.kind, `Unlock ${card.name}?`))) return;
				set({ locked: !lk.locked });
			}}
		>
			<Icon name={lk.locked ? 'unlock' : 'lock'} />
			{lk.locked ? 'Unlock' : 'Lock'}
		</button>
	{:else if card.control?.kind === 'timer'}
		{@const tm = card.control}
		<button
			class="wide"
			disabled={off}
			onclick={() =>
				commands.timer(
					id,
					tm.running ? { command: 'cancel' } : { command: 'start', duration_secs: tm.durationSecs }
				)}>{tm.running ? 'Cancel timer' : 'Start timer'}</button
		>
		{#if tm.running && core.since('0.1.81')}
			<button
				class="wide"
				disabled={off}
				onclick={() => commands.timer(id, { command: 'extend', duration_secs: 300 })}
				>5 more minutes</button
			>
		{/if}
	{:else if card.control?.kind === 'button'}
		{@const bt = card.control}
		<button
			class="wide"
			disabled={off}
			onclick={() => run({ id: bt.action, label: bt.label, confirm: bt.confirm, fields: [] })}
			>{ran === bt.action ? 'Done' : bt.label}</button
		>
	{/if}

	{#if card.control?.kind === 'play' || card.extras.some((e) => e.kind === 'transport')}
		{@const tr = card.extras.find((e) => e.kind === 'transport')}
		<div class="transport">
			{#if tr?.kind === 'transport' && tr.previous}
				<button
					class="round"
					aria-label="Previous"
					disabled={off}
					onclick={() => commands.act(id, tr.previous!)}><SkipBack size={20} /></button
				>
			{/if}
			{#if card.control?.kind === 'play'}
				{@const pl = card.control}
				<button
					class="round main"
					aria-label={pl.playing ? 'Pause' : 'Play'}
					disabled={off}
					onclick={() => commands.act(id, pl.action)}
				>
					{#if pl.playing}<Pause size={24} fill="currentColor" />{:else}<Play
							size={24}
							fill="currentColor"
						/>{/if}
				</button>
			{/if}
			{#if tr?.kind === 'transport' && tr.next}
				<button
					class="round"
					aria-label="Next"
					disabled={off}
					onclick={() => commands.act(id, tr.next!)}><SkipForward size={20} /></button
				>
			{/if}
		</div>
	{/if}

	{#each card.channels as ch (ch.attr)}
		<div class="row">
			<span>{ch.label}</span>
			<Toggle
				on={ch.on}
				label={ch.label}
				disabled={off}
				onchange={(on) => set({ [ch.attr]: on })}
			/>
		</div>
	{/each}

	{#each card.extras as e ('attr' in e ? e.attr : e.kind)}
		{#if e.kind === 'slider' && e.attr !== 'brightness_pct'}
			<BigBar
				label={e.label}
				value={e.value}
				min={e.min}
				max={e.max}
				step={e.step}
				unit={e.unit}
				disabled={off}
				oncommit={(v) => set({ [e.attr]: v })}
			/>
		{:else if e.kind === 'steps'}
			<div class="field">
				<span class="label">{e.label}</span>
				<div class="steps" role="radiogroup" aria-label={e.label}>
					{#each e.options as o (o)}
						<button
							role="radio"
							aria-checked={e.value === o}
							disabled={off}
							onclick={() => set({ [e.attr]: o })}>{o.replace(/[-_]/g, ' ')}</button
						>
					{/each}
				</div>
			</div>
		{/if}
	{/each}

	<!-- Everything else it can be set to. -->
	{#each view.controls as c (c.attr)}
		{#if c.kind === 'toggle'}
			<div class="row">
				<span>{c.label}</span>
				<Toggle
					on={want(c.attr, c.value) === true}
					label={c.label}
					disabled={off}
					onchange={(on) => set({ [c.attr]: on })}
				/>
			</div>
		{:else if c.kind === 'slider'}
			<BigBar
				label={c.label}
				value={Number(want(c.attr, c.value))}
				min={c.min}
				max={c.max}
				step={c.step}
				unit={c.unit}
				disabled={off}
				oncommit={(v) => set({ [c.attr]: v })}
			/>
		{:else if c.kind === 'choice'}
			<div class="field">
				<span class="label">{c.label}</span>
				{#if c.options.length <= 5}
					<div class="steps" role="radiogroup" aria-label={c.label}>
						{#each c.options as o (o.value)}
							<button
								role="radio"
								aria-checked={want(c.attr, c.value) === o.value}
								disabled={off}
								onclick={() => set({ [c.attr]: o.value })}>{o.label}</button
							>
						{/each}
					</div>
				{:else}
					<select
						aria-label={c.label}
						disabled={off}
						value={String(want(c.attr, c.value))}
						onchange={(ev) => set({ [c.attr]: ev.currentTarget.value })}
					>
						{#each c.options as o (o.value)}<option value={o.value}>{o.label}</option>{/each}
					</select>
				{/if}
			</div>
		{:else if c.kind === 'colour'}
			<div class="field">
				<span class="label">{c.label}</span>
				<div class="swatches">
					{#each SWATCHES as [label, css, xy] (label)}
						<button
							class="swatch"
							style:background={css}
							aria-label={label}
							aria-pressed={near(c.value, xy)}
							disabled={off}
							onclick={() => set({ [c.attr]: xy, on: true })}
						></button>
					{/each}
				</div>
			</div>
		{:else if c.kind === 'text'}
			<form
				class="field inline"
				onsubmit={(ev) => {
					ev.preventDefault();
					const v = new FormData(ev.currentTarget).get('v');
					set({ [c.attr]: String(v ?? '') });
				}}
			>
				<label class="label" for={`t-${c.attr}`}>{c.label}</label>
				<input id={`t-${c.attr}`} name="v" value={c.value} disabled={off} />
				<button class="pill" disabled={off}>Set</button>
			</form>
		{/if}
	{/each}

	<!-- What it can do, by the plugin's own grouping. -->
	{#snippet group(g: (typeof view.groups)[number])}
		<div class="actions">
			{#each g.actions as a (a.id)}
				{#if a.fields.length === 0}
					<button class="pill" disabled={off} onclick={() => run(a)}
						>{ran === a.id ? 'Done' : a.label}</button
					>
				{:else}
					<form
						class="action"
						onsubmit={(ev) => {
							ev.preventDefault();
							void run(a);
						}}
					>
						{#each a.fields as f (f.name)}
							{#if f.kind === 'choice'}
								<select
									aria-label={f.label}
									value={String(values[a.id]?.[f.name] ?? f.value)}
									onchange={(ev) => field(a.id, f.name, ev.currentTarget.value)}
								>
									{#each f.options as o (o.value)}<option value={o.value}>{o.label}</option>{/each}
								</select>
							{:else if f.kind === 'number'}
								<input
									type="number"
									aria-label={f.label}
									min={f.min}
									max={f.max}
									value={Number(values[a.id]?.[f.name] ?? f.value)}
									oninput={(ev) => field(a.id, f.name, Number(ev.currentTarget.value))}
								/>
							{:else if f.kind === 'toggle'}
								<label class="check"
									><input
										type="checkbox"
										checked={Boolean(values[a.id]?.[f.name] ?? f.value)}
										onchange={(ev) => field(a.id, f.name, ev.currentTarget.checked)}
									/>
									{f.label}</label
								>
							{:else}
								<input
									aria-label={f.label}
									placeholder={f.label}
									value={String(values[a.id]?.[f.name] ?? f.value)}
									oninput={(ev) => field(a.id, f.name, ev.currentTarget.value)}
								/>
							{/if}
						{/each}
						<button class="pill" disabled={off || !ready(a, values[a.id] ?? {})}
							>{ran === a.id ? 'Done' : a.label}</button
						>
					</form>
				{/if}
			{/each}
		</div>
	{/snippet}

	<!-- The first two groups open; the rest folded, so a TV's thirty actions
	     are all there without being a wall of buttons. -->
	{#each view.groups as g, i (g.title)}
		{#if i < 2}
			<section>
				<h3 class="section-label">{g.title}</h3>
				{@render group(g)}
			</section>
		{:else}
			<details class="group">
				<summary>{g.title}</summary>
				{@render group(g)}
			</details>
		{/if}
	{/each}

	{#if view.readings.length > 0}
		<section>
			<h3 class="section-label">Readings</h3>
			<dl>
				{#each view.readings as r (r.attr)}
					<div>
						<dt>{r.label}</dt>
						<dd>{r.value}</dd>
					</div>
				{/each}
			</dl>
		</section>
	{/if}

	{#if view.chart}
		<Chart
			deviceId={id}
			attr={view.chart.attr}
			label={view.chart.label}
			unit={view.chart.unit}
			bool={view.chart.bool}
			current={device.attributes[view.chart.attr]}
		/>
	{/if}

	<section>
		<h3 class="section-label">Activity</h3>
		{#if activity === null}
			<p class="quiet">…</p>
		{:else if lines.length === 0}
			<p class="quiet">Nothing since homeCore last started.</p>
		{:else}
			<ul class="activity">
				{#each lines as l (l.at + l.text)}
					<li><span class="num when">{time(l.at)}</span><span>{l.text}</span></li>
				{/each}
			</ul>
		{/if}
	</section>

	{#if view.more.length > 0}
		<details>
			<summary>More</summary>
			<dl>
				{#each view.more as r (r.attr)}
					<div>
						<dt>{r.label}</dt>
						<dd>{r.value}</dd>
					</div>
				{/each}
			</dl>
		</details>
	{/if}
</div>

