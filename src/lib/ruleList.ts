/**
 * The automations list (A2, doc 09 §3): each rule as a sentence, grouped by
 * its tags — which in this house are rooms (E9) — with what needs looking
 * at first, and families of rules that are one intent kept together (E4).
 */
import { displayName, type CoreDevice } from './devices.js';
import { found } from './settings.js';
import { knownPluginName } from './inventory.js';
import { plain, refsOf, sentence, tagOf, type House, type Phrase, type Rule } from './ruleWords.js';
import type { AutomationAlerts } from './alertStarts.js';

/** What the list knows of a rule's recent runs (from its history). */
export interface LastRuns {
	/** When it last did its steps. */
	ran?: string;
	/** When its trigger last matched, whether or not it ran. */
	tried?: string;
	/** Its last run had a step that failed. */
	failed?: string;
}

export interface Row {
	rule: Rule;
	words: Phrase;
	/** Ids it names that the house doesn't have. */
	missing: string[];
	/** Generated by a mode's definition: changed there, not here. */
	byMode?: string;
	/** Only sends messages — an alert time rule may do (E8). */
	alertish: boolean;
	family?: Family;
	/** Why it needs looking at, in words; empty when it doesn't. */
	trouble: string[];
	/** Everything search looks through. */
	text: string;
	/** Started by an alert: which, and whether it's waiting (`GET /alerts/automations`). */
	byAlert?: AutomationAlerts;
}

export interface Family {
	key: string;
	label: string;
	ids: string[];
}

export type Show = 'all' | 'attention' | 'off' | 'families' | 'alerts';

/** What homeCore says of an automation kept after its alert rule was deleted. */
export const alertDeleted = (r: Rule) => r.error?.startsWith('its alert was deleted') ?? false;

export function rowsOf(
	rules: Rule[],
	h: House,
	runs: Record<string, LastRuns> = {},
	byMode: Record<string, string> = {},
	byAlert: Record<string, AutomationAlerts> = {}
): Row[] {
	const families = familiesOf(rules);
	return rules.map((rule) => {
		const words = sentence(h, rule);
		const missing = refsOf(h, rule)
			.filter((r) => r.missing)
			.map((r) => r.id);
		const trouble: string[] = [];
		if (alertDeleted(rule))
			trouble.push('Its alert was deleted — choose another trigger or delete it');
		else if (rule.error) trouble.push(`homeCore can’t run it: ${rule.error}`);
		if (missing.length)
			trouble.push(
				missing.length === 1
					? `Names “${shortId(missing[0]!)}”, which the house has no device for`
					: `Names ${missing.length} devices the house doesn’t have`
			);
		const failed = runs[rule.id]?.failed;
		if (failed) trouble.push(`A step failed when it last ran: ${failed}`);
		const tags = rule.tags ?? [];
		return {
			rule,
			words,
			missing,
			byMode: byMode[rule.id],
			alertish: onlyTells(rule),
			family: families.get(rule.id),
			trouble,
			byAlert: byAlert[rule.id],
			text: `${rule.name} ${plain(words)} ${tags.join(' ')} ${refsOf(h, rule)
				.map((r) => r.id)
				.join(' ')}`
		};
	});
}

const shortId = (id: string) => (id.startsWith('DELETED:') ? id.slice(8) : id);

/** Whether a row shows for the search and the chip. */
export function shows(row: Row, query: string, show: Show): boolean {
	if (!found(row.text, query)) return false;
	if (show === 'attention') return row.trouble.length > 0;
	if (show === 'off') return !row.rule.enabled;
	if (show === 'families') return row.family !== undefined;
	if (show === 'alerts') return row.byAlert !== undefined;
	return true;
}

export function counts(rows: Row[], query: string): Record<Show, number> {
	const n = (show: Show) => rows.filter((r) => shows(r, query, show)).length;
	return {
		all: n('all'),
		attention: n('attention'),
		off: n('off'),
		families: n('families'),
		alerts: n('alerts')
	};
}

// ---- groups: by tag (E9) ----

export interface Group {
	/** The tag, or '' for rules with none. */
	tag: string;
	title: string;
	/** Rows, with a family's members together in the family's place. */
	items: Item[];
	count: number;
}
export type Item = { row: Row } | { family: Family; rows: Row[] };

/**
 * One group per tag, rooms first (a tag that names a room), then the other
 * tags, then the untagged. A rule with two tags is in both — it belongs to
 * two rooms.
 */
export function groupsOf(rows: Row[], roomNames: string[] = []): Group[] {
	const rooms = new Set(roomNames.map((n) => n.toLowerCase()));
	const byTag = new Map<string, Row[]>();
	for (const row of rows) {
		const tags = row.rule.tags?.length ? row.rule.tags : [''];
		for (const tag of tags) byTag.set(tag, [...(byTag.get(tag) ?? []), row]);
	}
	const rank = (tag: string) => (tag === '' ? 2 : rooms.has(tag.toLowerCase()) ? 0 : 1);
	return [...byTag.entries()]
		.sort(([a], [b]) => rank(a) - rank(b) || a.localeCompare(b))
		.map(([tag, list]) => ({
			tag,
			title: tag === '' ? 'Not tagged' : tag[0]!.toUpperCase() + tag.slice(1),
			items: itemsOf(list),
			count: list.length
		}));
}

function itemsOf(rows: Row[]): Item[] {
	const sorted = [...rows].sort((a, b) => a.rule.name.localeCompare(b.rule.name));
	const out: Item[] = [];
	const placed = new Set<string>();
	for (const row of sorted) {
		const f = row.family;
		const kin = f ? sorted.filter((r) => r.family?.key === f.key) : [];
		if (f && kin.length > 1) {
			if (placed.has(f.key)) continue;
			placed.add(f.key);
			out.push({ family: f, rows: kin });
		} else out.push({ row });
	}
	return out;
}

// ---- families (E4) ----

const VARIANT = /(?:\s+-\s+|\s+)(on|off|day|night|morning|afternoon|evening)$/;

/** A name with what distinguishes a family member taken out. */
export function familyKey(name: string): string {
	let k = name
		.toLowerCase()
		.replace(/\([^)]*\)/g, ' ')
		.replace(/[—–]/g, '-')
		.replace(/\d+/g, '#')
		.replace(/\s+/g, ' ')
		.trim();
	for (let prev = ''; prev !== k;) {
		prev = k;
		k = k.replace(VARIANT, '').replace(/[\s-]+$/, '');
	}
	return k;
}

/**
 * Rules that look like one intent: names alike but for a number, an on/off
 * or a time of day ("Btn1 … On", "Btn3 … Off"; "(Morning)", "(Afternoon)"),
 * and re-checks when homeCore starts. A guess, shown as one — never acted
 * on without someone saying so.
 */
export function familiesOf(rules: Rule[]): Map<string, Family> {
	const byKey = new Map<string, Rule[]>();
	for (const r of rules) {
		const key = tagOf(r.trigger)[0] === 'SystemStarted' ? '\u0000startup' : familyKey(r.name);
		byKey.set(key, [...(byKey.get(key) ?? []), r]);
	}
	const out = new Map<string, Family>();
	for (const [key, members] of byKey) {
		if (members.length < 2) continue;
		const family: Family = {
			key,
			label:
				key === '\u0000startup' ? 'When homeCore starts' : commonName(members.map((m) => m.name)),
			ids: members.map((m) => m.id)
		};
		for (const m of members) out.set(m.id, family);
	}
	return out;
}

/** What family members' names share: "Keypad lutron_72", "OH1 Timer Close". */
export function commonName(names: string[]): string {
	let p = names[0] ?? '';
	for (const n of names) while (!n.startsWith(p)) p = p.slice(0, -1);
	// A whole name is a whole word; otherwise back off to the last whole word.
	if (!names.includes(p) && !/[\s\-—–(]$/.test(p)) p = p.replace(/\S*$/, '');
	return p.replace(/[\s\-—–(]+$/, '').trim() || names[0]!;
}

// ---- rules that are really alerts (E8) ----

/** Whether a rule's steps only tell someone (and wait, and re-check). */
export function onlyTells(r: Rule): boolean {
	// Started by an alert, a message is the point: the alert can't do it itself.
	const triggers = [r.trigger, ...(r.triggers ?? [])];
	if (triggers.some((x) => tagOf(x)[0].startsWith('Alert'))) return false;
	let tells = false;
	const leaves = (a: unknown): boolean => {
		const [kind, f] = tagOf(a);
		if (kind === 'Notify') return (tells = true);
		if (kind === 'Delay' || kind === 'LogMessage' || kind === 'Comment') return true;
		if (kind === 'Conditional')
			return [...(f.then_actions ?? []), ...(f.else_actions ?? [])].every(leaves);
		return false;
	};
	const all = (r.actions ?? []).every((a) => leaves(a.action));
	return all && tells;
}

// ---- the house, for phrasing ----

/**
 * The phrasing's view of the house. A rule may name a device as homeCore
 * resolves it when it loads the rule (`rule_resolver.rs`): by id, by its
 * name in rules (`kitchen.ceiling`), or by its name when only one device
 * has it — so "bathroom" is the speaker whose name in rules that is.
 */
export function houseOf(
	byId: Record<string, CoreDevice>,
	scenes: { id: string; name: string }[] = [],
	rules: { id: string; name: string }[] = [],
	alertKinds: { plugin_id: string; topic: string; label: string }[] = [],
	describeStep?: (
		device: (id: string) => CoreDevice | undefined,
		ids: string[],
		state: unknown
	) => string | undefined,
	alertRules: { id: string; name: string }[] = []
): House {
	const byCanonical = new Map<string, CoreDevice>();
	const byName = new Map<string, CoreDevice | null>();
	const note = (name: string, d: CoreDevice) => {
		const k = nameKey(name);
		byName.set(k, byName.has(k) && byName.get(k) !== d ? null : d);
	};
	for (const d of Object.values(byId)) {
		if (d.canonical_name) byCanonical.set(d.canonical_name, d);
		note(d.name, d);
		if (d.name_override) note(d.name_override, d);
	}
	const device = (id: string) =>
		byId[id] ?? byCanonical.get(id) ?? byName.get(nameKey(id)) ?? undefined;
	return {
		device,
		describeStep: describeStep ? (ids, state) => describeStep(device, ids, state) : undefined,
		scene: (id) => scenes.find((s) => s.id === id)?.name,
		rule: (id) => rules.find((r) => r.id === id)?.name,
		alertKind: (plugin, topic) =>
			alertKinds.find((k) => k.plugin_id === plugin && k.topic === topic)?.label,
		plugin: knownPluginName,
		alertRule: (id) => alertRules.find((r) => r.id === id)?.name
	};
}

/** homeCore's `normalize_name_segment`: "Living Room Lamp" → "living_room_lamp". */
export const nameKey = (s: string) =>
	s
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, '_')
		.replace(/^_+|_+$/g, '');

/**
 * The device a rule probably meant by an id the house lacks: one whose id
 * name is it, or whose id ends with it — "bathroom" for the speaker
 * `sonos_bathroom` called "Bathroom". Only when exactly one fits.
 */
export function likelyFor(id: string, byId: Record<string, CoreDevice>): CoreDevice | undefined {
	const want = id.replace(/^DELETED:/, '').toLowerCase();
	const said = want.replace(/[_-]+/g, ' ');
	const all = Object.values(byId);
	// Strongest first: its name, its name in rules, then the end of its id.
	for (const fits of [
		(d: CoreDevice) => displayName(d).toLowerCase() === said,
		(d: CoreDevice) => d.canonical_name?.toLowerCase().endsWith(`.${want}`) === true,
		(d: CoreDevice) => d.device_id.toLowerCase().endsWith(`_${want}`)
	]) {
		const found = all.filter(fits);
		if (found.length === 1) return found[0];
		if (found.length > 1) return undefined;
	}
	return undefined;
}

/** The rule with every mention of device `from` made `to` — fields and scripts alike. */
export function repoint<T>(rule: T, from: string, to: string): T {
	const quoted = new RegExp(
		`device_state\\(\\s*"${from.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"`,
		'g'
	);
	const walk = (v: unknown, key: string): unknown => {
		if (typeof v === 'string') {
			if ((key === 'device_id' || key === 'device_ids' || key === 'mode_id') && v === from)
				return to;
			return v.replace(quoted, `device_state("${to}"`);
		}
		if (Array.isArray(v)) return v.map((x) => walk(x, key));
		if (v !== null && typeof v === 'object')
			return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, walk(x, k)]));
		return v;
	};
	return walk(rule, '') as T;
}

// ---- time, as the list says it ----

/** "12 min ago", "today 15:39", "yesterday 08:49", "12 Oct". */
export function whenText(iso: string | undefined, now = Date.now()): string {
	if (!iso) return '';
	const at = new Date(iso);
	const ms = now - at.getTime();
	if (!Number.isFinite(ms)) return '';
	if (ms < 60_000) return 'just now';
	if (ms < 3_600_000) return `${Math.floor(ms / 60_000)} min ago`;
	const day = dayOf(iso, now);
	const time = at.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', hour12: false });
	if (day === 'Today') return `today ${time}`;
	if (day === 'Yesterday') return `yesterday ${time}`;
	return day;
}

/** "Today", "Yesterday", "12 Oct". */
export function dayOf(iso: string, now = Date.now()): string {
	const at = new Date(iso);
	const start = new Date(now);
	start.setHours(0, 0, 0, 0);
	const days = Math.floor((start.getTime() - at.getTime()) / 86_400_000) + 1;
	if (at.getTime() >= start.getTime()) return 'Today';
	if (days === 1) return 'Yesterday';
	return at.toLocaleDateString([], { day: 'numeric', month: 'short' });
}
